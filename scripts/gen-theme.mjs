// Writes the brand colour scheme (light + dark, prefers-color-scheme) for src/styles/site.css.
import { mkdirSync, writeFileSync } from 'node:fs';
import { createTheme } from '@kyralabs/m3e-tokens/theme';
import { brand } from '../src/brand.mjs';

const out = new URL('../src/styles/generated/theme.css', import.meta.url);
mkdirSync(new URL('.', out), { recursive: true });
const { cssText } = createTheme({ ...brand, mode: 'system' });
writeFileSync(out, `/* Generated by scripts/gen-theme.mjs from src/brand.mjs. Do not edit. */\n${cssText}`);
console.log(`theme: ${brand.seed} (${brand.variant}) -> src/styles/generated/theme.css`);
